import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { sourceSchema } from "../src/lib/feed";

const root = new URL("../", import.meta.url);
const raw = await readFile(new URL("sources/registry.json", root), "utf8");
const registry = JSON.parse(raw) as (ReturnType<typeof sourceSchema.parse> & {
  verification: { checked_at: string; status: string; warnings: string[] };
})[];
for (const source of registry) {
  sourceSchema.parse(source);
  if (source.verification.status !== "verified" || source.exclude_reason)
    throw new Error(`Unverified source: ${source.id}`);
}
if (!registry.length) throw new Error("Registry must not be empty");
if (
  new Set(registry.map((s) => s.id)).size !== registry.length ||
  new Set(registry.map((s) => s.feed_url)).size !== registry.length
)
  throw new Error("Duplicate source ID or feed URL");
const hash = createHash("sha256").update(raw).digest("hex");
const migration = process.argv
  .find((value) => value.startsWith("--migration="))
  ?.slice(12);
if (!migration || !/^\d{12}_[a-z0-9_]+\.sql$/.test(migration))
  throw new Error("Pass a new --migration=YYYYMMDDHHMM_name.sql");
const sql = `-- Generated by npm run sources:build. Do not edit manually.
-- Registry SHA-256: ${hash}
-- ${registry.length} live-verified source streams. Existing operator enable/disable choices are preserved.
insert into public.sources(id,name,feed_url,allowed_origins,category,channel,adapter,homepage,discovery_url,discovery_notes,
  rationale,limitations,verification,item_url_prefix,poll_interval_minutes,max_feed_bytes)
select r.id,r.name,r.feed_url,array(select jsonb_array_elements_text(r.allowed_origins)),r.category,r.channel,r.adapter,
  r.homepage,r.discovery_url,r.discovery_notes,r.rationale,r.limitations,r.verification,r.item_url_prefix,r.poll_interval_minutes,r.max_feed_bytes
from jsonb_to_recordset($registry$${JSON.stringify(registry)}$registry$::jsonb)
  as r(id text,name text,feed_url text,allowed_origins jsonb,category text,channel text,adapter text,homepage text,
    discovery_url text,discovery_notes text,rationale text,limitations text,verification jsonb,item_url_prefix text,
    poll_interval_minutes integer,max_feed_bytes integer)
on conflict(id) do update set name=excluded.name,feed_url=excluded.feed_url,allowed_origins=excluded.allowed_origins,
  category=excluded.category,channel=excluded.channel,adapter=excluded.adapter,homepage=excluded.homepage,
  discovery_url=excluded.discovery_url,discovery_notes=excluded.discovery_notes,rationale=excluded.rationale,
  limitations=excluded.limitations,verification=excluded.verification,item_url_prefix=excluded.item_url_prefix,
  poll_interval_minutes=excluded.poll_interval_minutes,max_feed_bytes=excluded.max_feed_bytes;\nupdate public.sources set enabled=false where id not in (select value->>'id' from jsonb_array_elements($registry$${JSON.stringify(registry)}$registry$::jsonb));
`;
if (JSON.stringify(registry).includes("$registry$"))
  throw new Error("Unsafe SQL delimiter in registry");
await writeFile(new URL("supabase/migrations/" + migration, root), sql, {
  flag: "wx",
});
const candidates = JSON.parse(
  await readFile(new URL("sources/candidates.json", root), "utf8"),
) as { id: string; name: string; feed_url: string }[];
const checks = JSON.parse(
  await readFile(new URL("sources/verification.json", root), "utf8"),
) as { id: string; status: string; reason?: string }[];
const counts = (key: "category" | "channel") =>
  [...new Set(registry.map((s) => s[key]))]
    .sort()
    .map(
      (value) =>
        [value, registry.filter((s) => s[key] === value).length] as const,
    );
const escape = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
let report = `# Source coverage audit\n\n${registry.length} source streams accepted from ${candidates.length} curated candidates. These are streams, not distinct vendors or a claim of comprehensive vulnerability coverage. A project may have both a release stream and an advisory stream.\n\nVerification window: ${registry.map((s) => s.verification.checked_at).sort()[0]} through ${registry
  .map((s) => s.verification.checked_at)
  .sort()
  .at(
    -1,
  )}. Registry SHA-256: \`${hash}\`.\n\n## What verification means\n\nEvery enabled source returned parseable RSS/Atom and at least one usable document through the same adapter used by ingestion. Inline release feeds were checked across up to 30 entries; article feeds required a successful article fetch and extraction among the first three entries. Each check records a sample URL, text hash, text length, item count, and warnings. This is transport/parser verification, not a live LLM accuracy evaluation or an uptime guarantee.\n\nCandidates were selected for deployed application attack surfaces, runtime/standard-library exposure, transitive parsing/authentication dependencies, privileged infrastructure roles, or official remediation notices. Upstream repositories and publisher pages are retained as provenance. Arbitrary security-news aggregation sites are not used to inflate coverage.\n\n## Channel mix\n\n| Channel | Streams | Meaning |\n| --- | ---: | --- |\n`;
const meanings = {
  "security-advisories":
    "Dedicated advisory or public coordination stream; may also contain non-actionable notices.",
  "mixed-announcements":
    "Official news/release stream that may contain security fixes.",
  "release-notes":
    "Upstream release bodies; not equivalent to repository security-advisory coverage.",
};
for (const [channel, count] of counts("channel"))
  report += `| ${channel} | ${count} | ${meanings[channel as keyof typeof meanings]} |\n`;
report += "\n## Categories\n\n| Category | Streams |\n| --- | ---: |\n";
for (const [category, count] of counts("category"))
  report += `| ${category} | ${count} |\n`;
report +=
  "\n## Maintenance follow-up\n\nGitHub streams with a latest dated entry older than one year received an additional repository metadata review (see `sources/maintenance-review.json`). Archived or explicitly abandoned endpoints were excluded or a documented successor was added. The current Element Synapse endpoint was checked instead of the archived Matrix repository; it was excluded because the checked entries contained only version tags. A quiet but unarchived release stream remains eligible with a staleness warning; this does not assert that every repository is actively maintained.\n\n## Known limitations\n\n- GitHub release feeds are reused for their inline notes. GitHub tag-only entries are skipped, and projects whose checked feed contains no substantive release notes are excluded. External changelogs, assets, commits, and repository security advisories are not crawled automatically.\n- Dedicated vendor pages without a working RSS/Atom endpoint need a separate adapter. Rejected candidates below are not enabled or counted. A rejection can reflect network access, temporary failure, or an unsupported format—not the absence of a vendor advisory service.\n- Updates are watched only while entries remain in the current feed window. Every entry in a fetched feed is durably staged. Publishers can still remove entries between polls; monitor lag and add a historical API adapter where necessary.\n- Exact-quote validation reduces invented fields but cannot prove correct product/version association. Production model evaluation remains required.\n- No vendor coverage is inferred from a distribution package advisory: Debian or Ubuntu backport versions remain distinct from upstream fixed versions.\n- This catalog does not yet include a structured OSV adapter.\n\n## Enabled catalog\n\n| Source | Category | Channel | Adapter | Feed | Warnings |\n| --- | --- | --- | --- | --- | --- |\n";
for (const s of registry)
  report += `| [${escape(s.name)}](${s.homepage}) | ${s.category} | ${s.channel} | ${s.adapter} | [RSS/Atom](${s.feed_url}) | ${escape(s.verification.warnings?.join("; ") ?? "")} |\n`;
report +=
  "\n## Excluded candidates\n\n| Source | Candidate endpoint | Reason |\n| --- | --- | --- |\n";
for (const check of checks.filter((c) => c.status === "rejected")) {
  const s = candidates.find((candidate) => candidate.id === check.id)!;
  report += `| ${escape(s.name)} | [Endpoint](${s.feed_url}) | ${escape(check.reason ?? "Unverified")} |\n`;
}
await writeFile(new URL("docs/source-coverage.md", root), report);
console.log(
  JSON.stringify({
    sources: registry.length,
    candidates: candidates.length,
    channels: Object.fromEntries(counts("channel")),
    registry_sha256: hash,
  }),
);
