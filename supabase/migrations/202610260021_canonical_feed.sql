create table public.feed_items (
  id text primary key check(id ~ '^[a-f0-9]{64}$'),
  cursor bigint generated by default as identity unique,
  revision integer not null,
  created_at timestamptz not null,
  updated_at timestamptz not null,
  source_published_at timestamptz,
  active boolean not null,
  replaced_by text[] not null,
  kind text not null check(kind in ('advisory','patch','mitigation','withdrawal','other')),
  title text not null, summary text not null,
  product_names text[] not null, affected_versions text[] not null, fixed_versions text[] not null,
  cve_ids text[] not null, fixed_cve_ids text[] not null, technology_ids text[] not null,
  source_ids text[] not null, source_urls text[] not null,
  severity text not null check(severity in ('critical','high','medium','low','unknown')),
  cvss jsonb, known_exploited boolean not null, fix_available boolean not null, important boolean not null,
  records jsonb not null check(jsonb_typeof(records)='array'),
  record_ids text[] not null, identity_keys text[] not null,
  type_keys text[] not null, severity_keys text[] not null, cve_keys text[] not null,
  technology_keys text[] not null, source_keys text[] not null, fix_key boolean not null, important_key boolean not null,
  search_document tsvector generated always as (
    to_tsvector('simple',title||' '||summary)||jsonb_to_tsvector('simple',records,'["string"]'::jsonb)
  ) stored
);
