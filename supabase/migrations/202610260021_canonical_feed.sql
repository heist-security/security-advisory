-- Fence the old writer during the resumable import. In-flight jobs are returned
-- to the durable queue; they will be processed by the new application.
create or replace function public.finish_document(document_id bigint,token uuid,result jsonb,model_name text)
returns void language sql set search_path=public as $$
  update documents set status='pending',attempts=greatest(attempts-1,0),available_at=now()+interval '5 minutes',
    lease_token=null,leased_until=null where id=document_id and lease_token=token and status='processing';
$$;
create function public.guard_feed_cutover() returns trigger language plpgsql set search_path=public as $$
begin
  if new.status='processing' and exists(select 1 from feed_migration where completed_at is null) then
    raise exception 'Feed migration in progress';
  end if;
  return new;
end; $$;
create trigger guard_feed_cutover before update of status on public.documents for each row execute function public.guard_feed_cutover();

-- Durable queue mechanics only. Paid and deterministic extraction share one
-- fenced claim; only publisher work consumes the database-enforced budget.
create function public.claim_ingest_document(source_ids text[],hourly_budget integer default null)
returns setof public.documents language plpgsql set search_path=public as $$
declare job documents; bucket timestamptz:=date_trunc('hour',now(),'UTC'); used integer;
begin
  if exists(select 1 from feed_migration where completed_at is null) then return; end if;
  if hourly_budget is not null then
    if hourly_budget<1 or hourly_budget>10000 then raise exception 'Invalid extraction budget'; end if;
    perform pg_advisory_xact_lock(719432002);
    delete from extraction_budget where hour<now()-interval '7 days';
    insert into extraction_budget(hour) values(bucket) on conflict do nothing;
    select attempts into used from extraction_budget where hour=bucket for update;
    if used>=hourly_budget then return; end if;
  end if;
  update documents set status='failed',last_error='lease_expired',lease_token=null,leased_until=null
    where status='processing' and leased_until<=now() and attempts>=5;
  update documents set status='processing',attempts=attempts+1,lease_token=gen_random_uuid(),leased_until=now()+interval '3 minutes'
  where id=(select d.id from documents d join sources s on s.id=d.source_id
    where s.enabled and d.source_id=any(source_ids) and d.attempts<5 and d.available_at<=now()
      and (d.status='pending' or (d.status='processing' and d.leased_until<=now()))
    order by d.id for update of d skip locked limit 1) returning * into job;
  if found then
    if hourly_budget is not null then update extraction_budget set attempts=attempts+1 where hour=bucket; end if;
    return next job;
  end if;
end; $$;

create function public.finish_feed_migration() returns void language plpgsql set search_path=public as $$
declare old_function record;
begin
  perform pg_advisory_xact_lock(719432001);
  if exists(select 1 from feed_migration where completed_at is not null) then return; end if;
  if exists(select 1 from events where id>(select last_event_id from feed_migration)) then raise exception 'Feed import incomplete'; end if;
  -- Remove the live group/read-model architecture. Original source revisions
  -- stay in a private, read-only archive; no running application depends on it.
  drop table advisory_feed_members,advisory_update_members,advisory_feed_backfill;
  drop table advisory_group_updates,advisory_groups,advisory_group_members,advisory_group_backfill;
  drop table technology_catalog,technology_backfill,priority_backfill;
  alter table events drop column search_document cascade;
  for old_function in select p.oid::regprocedure::text signature from pg_proc p join pg_namespace n on n.oid=p.pronamespace
    where n.nspname='public' and p.proname=any(array[
      'finish_document','claim_document','claim_vendor_document','feed_health',
      'event_search_document','event_cve_links','event_priority','prepare_event_priority','refresh_linked_priority','severity_rank',
      'technology_key','text_union','canonical_technology','technology_family_keys','technology_families','technology_product_name','technology_catalog_search',
      'register_event_technologies','backfill_event_priority','backfill_event_technologies',
      'advisory_group_anchor','advisory_scopes_match','refresh_advisory_group','sync_advisory_group','publish_advisory_group',
      'backfill_advisory_groups','public_group_event','group_event_matches','query_advisory_groups','query_advisory_groups_legacy',
      'advisory_sitemap_parts','refresh_advisory_feed_members','sync_advisory_feed_members','refresh_advisory_update_members',
      'sync_advisory_update_members','sync_advisory_member_filters','backfill_advisory_feed','advisory_feed_where',
      'query_advisory_current','query_advisory_updates'])
  loop execute 'drop function if exists '||old_function.signature||' cascade'; end loop;
  create schema if not exists feed_archive;
  revoke all on schema feed_archive from public,anon,authenticated;
  grant usage on schema feed_archive to service_role;
  alter table events set schema feed_archive;
  alter table advisories set schema feed_archive;
  revoke all on feed_archive.events,feed_archive.advisories from public,anon,authenticated,service_role;
  grant select on feed_archive.events,feed_archive.advisories to service_role;
  update feed_migration set completed_at=clock_timestamp();
end; $$;

