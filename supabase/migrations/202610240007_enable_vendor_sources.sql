-- Paid work must not queue behind structured backfills or unselected publishers.
-- Share the same transaction lock and hourly counter as the legacy claim RPC.
create function public.claim_vendor_document(hourly_limit integer, source_ids text[])
returns setof public.documents language plpgsql set search_path=public as $$
declare bucket timestamptz:=date_trunc('hour',now(),'UTC'); used integer; job documents;
begin
  if hourly_limit is null or hourly_limit<1 or hourly_limit>10000 then
    raise exception 'Invalid hourly extraction limit';
  end if;
  if coalesce(cardinality(source_ids),0)=0 then return; end if;
  perform pg_advisory_xact_lock(719432002);
  delete from extraction_budget where hour<now()-interval '7 days';
  insert into extraction_budget(hour) values(bucket) on conflict do nothing;
  select attempts into used from extraction_budget where hour=bucket for update;
  if used>=hourly_limit then return; end if;
  update documents set status='failed',last_error='lease_expired'
    where source_id=any(source_ids) and source_id not in ('core-osv','core-cve','core-kev')
      and status='processing' and leased_until<=now() and attempts>=5;
  update documents set status='processing',attempts=attempts+1,
    lease_token=gen_random_uuid(),leased_until=now()+interval '3 minutes'
  where id=(select d.id from documents d join sources s on s.id=d.source_id
    where s.enabled and d.source_id=any(source_ids)
      and d.source_id not in ('core-osv','core-cve','core-kev')
      and d.attempts<5 and d.available_at<=now()
      and (d.status='pending' or (d.status='processing' and d.leased_until<=now()))
    order by d.id for update of d skip locked limit 1)
  returning * into job;
  if found then
    update extraction_budget set attempts=attempts+1 where hour=bucket;
    return next job;
  end if;
end; $$;
revoke all on function public.claim_vendor_document(integer,text[]) from public,anon,authenticated;
grant execute on function public.claim_vendor_document(integer,text[]) to service_role;
commit;
